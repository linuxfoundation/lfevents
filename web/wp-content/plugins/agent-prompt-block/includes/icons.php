/**
 * Renders an inline SVG icon.
 *
 * @param string $name       Icon name from lf_agent_prompt_icon_paths().
 * @param string $css_class  CSS class for the <svg> element.
 * @param string $fill       Fill value, or 'stroke' to render as a stroked outline icon.
 * @return string Escaped SVG markup, or an empty string for unknown icons.
 */
function lf_agent_prompt_icon( $name, $css_class = '', $fill = 'currentColor' ) {
	$paths = lf_agent_prompt_icon_paths( $name );

	if ( empty( $paths ) ) {
		return '';
	}

	$viewbox = in_array( $name, array( 'chevron', 'external' ), true ) ? '0 0 20 20' : '0 0 24 24';
	$stroked = 'stroke' === $fill;

	$attrs = sprintf(
		'class="%s" viewBox="%s" xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false"',
		esc_attr( $css_class ),
		esc_attr( $viewbox )
	);

	if ( $stroked ) {
		$attrs .= ' fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"';
	} else {
		$attrs .= ' fill="' . esc_attr( $fill ) . '"';
	}

	$markup = '<svg ' . $attrs . '>';
	foreach ( $paths as $path ) {
		$markup .= '<path d="' . esc_attr( $path ) . '"></path>';
	}
	$markup .= '</svg>';

	return $markup;
}
